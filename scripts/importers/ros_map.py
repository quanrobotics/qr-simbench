"""Import any ROS occupancy map (map.yaml + image) as a QR layout file.

    python scripts/importers/ros_map.py MAP.yaml LAYOUT_ID [--stations N] [--unknown-occupied]

Occupied cells (and, with --unknown-occupied, unknown cells) are merged into box obstacles (greedy rectangles
on a 0.1 m grid), the map extent becomes the walls, and N stations are placed automatically in open floor
(farthest-point spread, at least 0.6 m from any obstacle). Edit the stations, then build the world with
`python scripts/build_world.py simulation/worlds/LAYOUT_ID.layout.yaml`.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import yaml
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
CELL = 0.1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("map_yaml", type=Path)
    ap.add_argument("layout_id")
    ap.add_argument("--stations", type=int, default=6)
    ap.add_argument("--unknown-occupied", action="store_true")
    a = ap.parse_args()
    meta = yaml.safe_load(a.map_yaml.read_text())
    img = Image.open(a.map_yaml.parent / meta["image"]).convert("L")
    res, (ox, oy) = float(meta["resolution"]), meta["origin"][:2]
    px = np.asarray(img, dtype=float) / 255.0
    occ_p = px if meta.get("negate") else 1.0 - px
    occ = occ_p > float(meta.get("occupied_thresh", 0.65))
    if a.unknown_occupied:
        occ |= occ_p > float(meta.get("free_thresh", 0.196))
    h, w = occ.shape
    f = max(1, round(CELL / res))  # downsample: a coarse cell is occupied if any pixel in it is
    gh, gw = h // f, w // f
    g = occ[: gh * f, : gw * f].reshape(gh, f, gw, f).any(axis=(1, 3))
    blocks, used = [], np.zeros_like(g)
    for r in range(gh):
        for c in range(gw):
            if not g[r, c] or used[r, c]:
                continue
            c2 = c
            while c2 + 1 < gw and g[r, c2 + 1] and not used[r, c2 + 1]:
                c2 += 1
            r2 = r
            while r2 + 1 < gh and g[r2 + 1, c:c2 + 1].all() and not used[r2 + 1, c:c2 + 1].any():
                r2 += 1
            used[r:r2 + 1, c:c2 + 1] = True
            cs = f * res
            x0, x1 = ox + c * cs, ox + (c2 + 1) * cs
            y1, y0 = oy + (h - r * f) * res, oy + (h - (r2 + 1) * f) * res
            blocks.append({"name": f"map_{len(blocks) + 1}", "x": round((x0 + x1) / 2, 3), "y": round((y0 + y1) / 2, 3),
                           "sx": round(x1 - x0, 3), "sy": round(y1 - y0, 3), "h": 1.5, "color": [0.55, 0.57, 0.6]})
    # stations: open floor at least 0.6 m from obstacles, spread out by farthest-point sampling
    k = 2 * round(0.6 / res) + 1
    free = np.asarray(Image.fromarray((~occ * 255).astype(np.uint8)).filter(ImageFilter.MinFilter(k))) > 0
    ys, xs = np.nonzero(free[::4, ::4])
    pts = np.c_[ox + xs * 4 * res, oy + (h - ys * 4) * res]
    stations = {}
    if len(pts):
        chosen = [pts[np.argmin(np.hypot(*(pts - pts.mean(0)).T))]]
        for _ in range(min(a.stations, len(pts)) - 1):
            d = np.min([np.hypot(*(pts - p).T) for p in chosen], axis=0)
            chosen.append(pts[np.argmax(d)])
        for i, (x, y) in enumerate(chosen, 1):
            stations[f"station_{i}"] = {"x": round(float(x), 2), "y": round(float(y), 2), "yaw": 0.0,
                                        "label": f"Station {i}", "color": [0.15, 0.45, 0.9]}
    layout = {"id": a.layout_id, "source": {"map": str(a.map_yaml), "note": "imported from a ROS occupancy map"},
              "bounds": {"x_min": round(ox, 2), "x_max": round(ox + w * res, 2),
                         "y_min": round(oy, 2), "y_max": round(oy + h * res, 2)},
              "wall": {"thickness": 0.2, "height": 2.0, "color": [0.8, 0.8, 0.82]}, "map_resolution": res,
              "blocks": blocks, "stations": stations, "actors": []}
    out = ROOT / "simulation/worlds" / f"{a.layout_id}.layout.yaml"
    out.write_text("# Generated by scripts/importers/ros_map.py\n" + yaml.safe_dump(layout, sort_keys=False, width=120))
    print(out, f"{len(blocks)} obstacles, {len(stations)} stations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
